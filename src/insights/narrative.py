"""Rule-based, template text. No LLM and no API key. Only restates numbers the system actually computed."""
import numpy as np

CAVEAT = ("This summary is generated by fixed rules from the model's outputs. It is not medical advice, "
          "not a diagnosis and not clinically validated.")
PROV_TEXT = {"historical": "a real historical record from the public PhysioNet 2019 dataset, replayed as a simulation",
             "synthetic": "SYNTHETIC demonstration data (not a real patient)",
             "uploaded": "data uploaded by the user (unverified source)",
             "live_entry": "a live-entry session: readings typed in by the user, each treated as the next hour"}
KEY_VITALS = [("HR", "heart rate", "beats/min"), ("Resp", "respiratory rate", "breaths/min"),
              ("MAP", "mean arterial pressure", "mm Hg"), ("Temp", "temperature", "deg C"), ("O2Sat", "oxygen saturation", "%")]


def risk_trend(risk_history, window=6):
    scores = [r["risk_score"] for r in risk_history[-window:] if r.get("risk_score") is not None]
    if len(scores) < 3:
        return "not enough data to judge", 0.0
    slope = float(np.polyfit(range(len(scores)), scores, 1)[0])
    return ("rising" if slope > 0.01 else "falling" if slope < -0.01 else "roughly stable"), slope


def summarize_patient(snap) -> list:
    if not snap.get("has_data"):
        return ["No observations have been replayed yet. Press Start or Step in the sidebar."]
    s, out = snap["state"], []
    out.append(f"{s['subject_id']} is {PROV_TEXT.get(snap.get('provenance'), 'of unknown provenance')}.")
    out.append(f"The twin has received {s['n_observations']} hourly observations (up to simulated hour {s['hour']}); "
               f"data quality in the latest hour is '{s['data_quality']}' and the twin status is '{s['status'].replace('_', ' ')}'.")
    for v, name, unit in KEY_VITALS:
        cur, b = s["latest_values"].get(v), s["baseline"].get(v)
        if cur is None:
            continue
        age = s["hours_since_measured"].get(v, 0)
        txt = f"Latest {name}: {cur:.1f} {unit}" + (f" (measured {age} h ago)" if age else "")
        if b:
            d = cur - b["baseline_mean"]
            txt += f"; the patient's own early baseline is {b['baseline_mean']:.1f} ({d:+.1f})."
        out.append(txt)
    r = s["risk"]
    if r:
        label, _ = risk_trend(snap["risk_history"])
        flagged_h = sum(1 for x in snap["risk_history"] if x.get("flagged"))
        out.append(f"Model risk score ({r['model_name']}): {r['risk_score']:.2f} vs threshold {r['threshold']:.2f}; the recent "
                   f"trend is {label}. The threshold was crossed in {flagged_h} of {len(snap['risk_history'])} replayed hours. "
                   "The score is a ranking score, not a probability.")
    else:
        out.append("No risk model is loaded, so only anomaly detection is active.")
    if s["deviations"]:
        out.append("Currently unusual versus the patient's own baseline: " +
                   "; ".join(f"{d['variable']} ({d['direction']} baseline, z={d['z']:.1f})" for d in s["deviations"][:3]) + ".")
    al = snap["alerts"]
    if al:
        c = {k: sum(1 for a in al if a["severity"] == k) for k in ("critical", "warning", "info")}
        pend = sum(1 for a in al if a["status"] in ("active", "escalated"))
        out.append(f"Alerts so far: {c['critical']} critical, {c['warning']} warning, {c['info']} info; {pend} still need human review.")
    out.append(CAVEAT)
    return out


def explain_prediction(snap) -> list:
    if not snap.get("has_data") or not snap["state"]["risk"]:
        return ["No prediction is available yet."]
    r = snap["state"]["risk"]
    side = "at or above" if r["flagged"] else "below"
    out = [f"At simulated hour {r['last_hour_used']} the model used {r['n_observations_used']} observations (hours 0-{r['last_hour_used']}; "
           f"nothing from later hours) and produced {r['risk_score']:.2f}, {side} its threshold of {r['threshold']:.2f}."]
    tf = r.get("top_factors") or []
    if tf:
        out.append("Largest contributions in this linear model (association, not causation): " +
                   ", ".join(f"{f['feature']} ({f['contribution']:+.2f})" for f in tf) + ".")
    else:
        out.append(f"No per-prediction explanation is available for the '{r['model_name']}' model, so none is shown.")
    return out


def explain_whatif(cmp) -> list:
    adj = ", ".join(f"{k} {v:+g}" for k, v in cmp["adjustments"].items()) or "no changes"
    b, s = cmp["baseline"]["risk_score"].iloc[-1], cmp["scenario"]["risk_score"].iloc[-1]
    out = [f"Scenario: {adj}, applied to measured values from hour {cmp['start_hour']} onward.",
           f"At hour {cmp['current_hour']} the model score moves from {b:.2f} (observed) to {s:.2f} (scenario), a change of {cmp['delta_last']:+.2f}; "
           f"the largest change at any replayed hour is {cmp['max_abs_delta']:.2f}.",
           f"Observed: {'above' if b >= cmp['threshold'] else 'below'} the threshold ({cmp['threshold']:.2f}); scenario: "
           f"{'above' if s >= cmp['threshold'] else 'below'}."]
    if not cmp["adjustments"]:
        out.append("No adjustment was selected, so both curves are identical.")
    out.append(cmp["note"] + " Real patients respond to treatment in ways this model cannot capture.")
    return out
